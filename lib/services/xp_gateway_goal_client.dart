// lib/services/xp_gateway_goal_client.dart
//
// Client adapter for the server-authoritative daily-goal XP endpoint.
//
// IMPORTANT:
// - Never sends a client-calculated XP amount.
// - Never sends a UID in the JSON body.
// - Firebase Auth ID token and App Check token are sent as headers.
// - The server derives the UID from the verified Firebase token and
//   calculates the XP from its trusted goal template.
//
// Requires the existing project files:
//   lib/data/courses/course_generator_config.dart
//   lib/services/backend_auth_headers.dart
//
// Backend contract:
//   POST {COURSE_BACKEND_URL}/xp/complete-goal
//   JSON body: {"careerId":"...", "goalId":"..."}
//   JSON response: {"success":true,"result":{"awarded":true,"xp":10,
//                    "eventId":"...", "totalXp":123, "isCompleted":true}}

import 'dart:async';
import 'dart:convert';

import 'package:firebase_auth/firebase_auth.dart';
import 'package:flutter/foundation.dart';
import 'package:http/http.dart' as http;

import '../data/courses/course_generator_config.dart';
import 'backend_auth_headers.dart';

class XpGatewayGoalResult {
  const XpGatewayGoalResult({
    required this.awarded,
    required this.xp,
    required this.eventId,
    required this.isCompleted,
    this.totalXp,
    this.reason,
  });

  final bool awarded;
  final int xp;
  final String eventId;
  final bool isCompleted;
  final int? totalXp;
  final String? reason;

  factory XpGatewayGoalResult.fromJson(Map<String, dynamic> json) {
    final awarded = json['awarded'];
    final xp = json['xp'];
    final eventId = json['eventId'];
    final isCompleted = json['isCompleted'];

    if (awarded is! bool ||
        xp is! num ||
        eventId is! String ||
        isCompleted is! bool) {
      throw const FormatException('Invalid XP Gateway result.');
    }

    final rawTotal = json['totalXp'];
    return XpGatewayGoalResult(
      awarded: awarded,
      xp: xp.toInt(),
      eventId: eventId,
      isCompleted: isCompleted,
      totalXp: rawTotal is num ? rawTotal.toInt() : null,
      reason: json['reason'] is String ? json['reason'] as String : null,
    );
  }
}

class XpGatewayGoalException implements Exception {
  const XpGatewayGoalException(this.message, {this.statusCode, this.code});

  final String message;
  final int? statusCode;
  final String? code;

  @override
  String toString() => message;
}

class XpGatewayGoalClient {
  XpGatewayGoalClient._();

  static http.Client _httpClient = http.Client();

  @visibleForTesting
  static set httpClient(http.Client client) => _httpClient = client;

  @visibleForTesting
  static String? backendBaseUrlOverride;

  static const Duration _requestTimeout = Duration(seconds: 20);

  static String get _baseUrl {
    var value =
        (backendBaseUrlOverride ?? CourseGeneratorConfig.backendBaseUrl).trim();
    while (value.endsWith('/')) {
      value = value.substring(0, value.length - 1);
    }
    return value;
  }

  static bool _isLocalHost(String host) =>
      host == 'localhost' || host == '127.0.0.1' || host == '10.0.2.2';

  static bool get isConfigured {
    final raw = _baseUrl;
    if (raw.isEmpty) return false;

    final uri = Uri.tryParse(raw);
    if (uri == null || uri.host.isEmpty) return false;

    if (uri.scheme == 'https') return true;
    return kDebugMode && uri.scheme == 'http' && _isLocalHost(uri.host);
  }

  /// Marks a trusted daily career goal complete.
  ///
  /// [careerId] must be the canonical CareerGoal.careerId used by the app.
  /// [goalId] must be the canonical daily goal id generated by
  /// LocalGoalGeneratorService:
  ///   {careerId}_{templateId}_{yyyy-MM-dd}_{index}
  ///
  /// XP is intentionally NOT accepted as an argument. The server looks up
  /// the trusted template and calculates the reward itself.
  static Future<XpGatewayGoalResult> completeGoal({
    required String careerId,
    required String goalId,
  }) async {
    if (!isConfigured) {
      throw const XpGatewayGoalException(
        'XP backend URL is not configured. Set COURSE_BACKEND_URL.',
      );
    }

    final safeCareerId = careerId.trim();
    final safeGoalId = goalId.trim();

    if (safeCareerId.isEmpty ||
        safeCareerId.length > 120 ||
        safeCareerId.contains('/') ||
        safeGoalId.isEmpty ||
        safeGoalId.length > 200 ||
        safeGoalId.contains('/')) {
      throw const XpGatewayGoalException('Invalid career or goal identifier.');
    }

    final user = FirebaseAuth.instance.currentUser;
    if (user == null) {
      throw const XpGatewayGoalException('Please sign in again.');
    }

    final uri = Uri.parse('$_baseUrl/xp/complete-goal');
    var forceRefresh = false;

    // Only refresh once after an authentication failure. The server endpoint
    // is idempotent, but this client deliberately does not retry other POST
    // failures automatically.
    for (var attempt = 0; attempt < 2; attempt++) {
      final currentUser = FirebaseAuth.instance.currentUser;
      if (currentUser == null || currentUser.uid != user.uid) {
        throw const XpGatewayGoalException(
          'Your sign-in session changed. Please try again.',
        );
      }

      final idToken = await currentUser
          .getIdToken(forceRefresh)
          .timeout(BackendAuthHeaders.tokenTimeout);
      if (idToken == null || idToken.isEmpty) {
        throw const XpGatewayGoalException(
          'Could not verify your sign-in. Please sign in again.',
        );
      }

      final appCheckToken = await BackendAuthHeaders.defaultAppCheckToken(
        forceRefresh: forceRefresh,
      );

      final headers = <String, String>{
        'Content-Type': 'application/json; charset=utf-8',
        'Accept': 'application/json',
        'Authorization': 'Bearer $idToken',
        if (appCheckToken != null && appCheckToken.isNotEmpty)
          BackendAuthHeaders.appCheckHeaderName: appCheckToken,
      };

      final response = await _httpClient
          .post(
            uri,
            headers: headers,
            body: jsonEncode(<String, String>{
              'careerId': safeCareerId,
              'goalId': safeGoalId,
            }),
          )
          .timeout(_requestTimeout);

      if (response.statusCode == 401 && !forceRefresh && attempt == 0) {
        forceRefresh = true;
        continue;
      }

      final decoded = _decodeResponse(response.body);
      if (response.statusCode < 200 || response.statusCode >= 300) {
        final message = decoded?['error'] is String
            ? decoded!['error'] as String
            : 'XP service request failed.';
        final code =
            decoded?['code'] is String ? decoded!['code'] as String : null;
        throw XpGatewayGoalException(
          message,
          statusCode: response.statusCode,
          code: code,
        );
      }

      if (decoded == null || decoded['success'] != true) {
        throw const XpGatewayGoalException(
          'XP service returned an invalid response.',
        );
      }

      final rawResult = decoded['result'];
      if (rawResult is! Map) {
        throw const XpGatewayGoalException(
          'XP service response is missing its result.',
        );
      }

      try {
        return XpGatewayGoalResult.fromJson(
          Map<String, dynamic>.from(rawResult),
        );
      } on FormatException {
        throw const XpGatewayGoalException(
          'XP service returned an invalid result.',
        );
      }
    }

    throw const XpGatewayGoalException(
      'Your session could not be verified. Please sign in again.',
      statusCode: 401,
    );
  }

  static Map<String, dynamic>? _decodeResponse(String body) {
    try {
      final decoded = jsonDecode(body);
      if (decoded is Map) return Map<String, dynamic>.from(decoded);
    } catch (_) {
      // Return null below; response bodies are never surfaced raw.
    }
    return null;
  }
}
