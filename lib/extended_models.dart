class SalaryInfo {
  final String country;
  final String role;
  final int minSalary;
  final int medianSalary;
  final int maxSalary;
  final String currency;

  const SalaryInfo({
    required this.country,
    required this.role,
    required this.minSalary,
    required this.medianSalary,
    required this.maxSalary,
    required this.currency,
  });
}
