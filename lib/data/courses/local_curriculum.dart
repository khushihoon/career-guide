// Curated OFFLINE curriculum used by the free local course generator.
//
// WHAT THIS IS
//   For each of the 10 careers whose levels in dynamic_career_paths.dart
//   have an empty `topics: const []` list, this file supplies 4 real,
//   career-specific topics per level (name + one-sentence description).
//   The two Cloud & DevOps careers already carry their own topic lists
//   in dynamic_career_paths.dart, so they are not repeated here.
//
// WHAT THIS IS NOT
//   This is NOT live AI output. The local generator turns these topics
//   into lessons, quizzes and projects using templates. If you want
//   richer lessons later, add more topics or longer descriptions here.
//
// RULES FOR EDITING
//   * Pure Dart only (no Flutter imports) so the backend can import it.
//   * Keep topic names unique inside one career.
//   * Use double-quoted strings and never write a dollar sign inside.
//   * Every level needs at least 4 topics (the tests check this).
// ══════════════════════════════════════════════════════════════════════

class CTopic {
  final String name;
  final String desc;
  const CTopic(this.name, this.desc);
}

class LocalCurriculum {
  LocalCurriculum._();

  static bool hasCareer(String careerId) => _byCareer.containsKey(careerId);

  static Iterable<String> get careerIds => _byCareer.keys;

  /// Topics for one level (level numbers start at 1). Null if unknown.
  static List<CTopic>? topicsFor(String careerId, int level) {
    final levels = _byCareer[careerId];
    if (levels == null || level < 1 || level > levels.length) return null;
    return levels[level - 1];
  }

  static int levelCount(String careerId) => _byCareer[careerId]?.length ?? 0;
}

