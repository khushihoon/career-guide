class Job {
  final String title;
  final String company;
  final String location;
  final String salary;
  final List<String> skills;
  final String type;
  final String icon;
  final String applyUrl;

  const Job({
    required this.title,
    required this.company,
    required this.location,
    required this.salary,
    required this.skills,
    required this.type,
    required this.icon,
    required this.applyUrl,
  });
}

class Course {
  final String title;
  final String platform;
  final String price;
  final bool isFree;
  final String url;
  final String icon;

  const Course({
    required this.title,
    required this.platform,
    required this.price,
    required this.isFree,
    required this.url,
    required this.icon,
  });
}

class AiTool {
  final String name;
  final String description;
  final String url;
  final String category;

  const AiTool({
    required this.name,
    required this.description,
    required this.url,
    required this.category,
  });
}

class RoadmapStep {
  final int number;
  final String title;
  final String subtitle;
  final List<String> topics;
  bool isDone;

  RoadmapStep({
    required this.number,
    required this.title,
    required this.subtitle,
    required this.topics,
    this.isDone = false,
  });
}

class ChatMessage {
  final String text;
  final bool isUser;
  final DateTime time;

  ChatMessage({
    required this.text,
    required this.isUser,
    required this.time,
  });
}

